"use client";

import {
  Check,
  Clipboard,
  ClipboardCheck,
  Copy,
  Minus,
  Plus,
  RotateCcw,
  ShieldCheck,
} from "lucide-react";
import { useEffect, useMemo, useRef, useState } from "react";
import {
  clampInvisibleCount,
  generateInvisibleText,
  INVISIBLE_CHARACTERS,
  type InvisibleCharacterId,
  verifyPasteBack,
} from "@/lib/invisible-text";
import { trackToolEvent, trackToolStarted } from "@/lib/tool-events-client";

const quickCounts = [1, 3, 5, 10, 25, 50];
const verificationLabels = {
  no_expected_payload: {
    title: "Copy a result first",
    detail: "The verifier needs the exact payload generated by this page for comparison.",
    tone: "neutral",
  },
  empty: {
    title: "Removed",
    detail: "Nothing was pasted back. The target may have removed the characters, or the clipboard may be empty.",
    tone: "warning",
  },
  exact_match: {
    title: "Exact match",
    detail: "The pasted-back code point sequence exactly matches the payload copied from BriefVu.",
    tone: "success",
  },
  changed_or_normalized: {
    title: "Changed or normalized",
    detail: "The result is not identical. The target may have removed, replaced, or normalized one or more code points.",
    tone: "warning",
  },
  extra_visible_content: {
    title: "Extra visible content",
    detail: "The pasted value includes a visible code point that was not part of the copied payload.",
    tone: "warning",
  },
} as const;

function fallbackCopy(payload: string): boolean {
  const field = document.createElement("textarea");
  field.value = payload;
  field.readOnly = true;
  field.setAttribute("aria-hidden", "true");
  field.style.position = "fixed";
  field.style.opacity = "0";
  field.style.pointerEvents = "none";
  document.body.appendChild(field);
  field.select();
  field.setSelectionRange(0, payload.length);
  let copied = false;
  try {
    copied = document.execCommand("copy");
  } catch {
    copied = false;
  } finally {
    field.remove();
  }
  return copied;
}

export function InvisibleTextTool() {
  const [selectedId, setSelectedId] = useState<InvisibleCharacterId>("hangul-filler");
  const [count, setCount] = useState(1);
  const [copyState, setCopyState] = useState<"idle" | "copied" | "failed">("idle");
  const [expectedPayload, setExpectedPayload] = useState<string | null>(null);
  const [pastedValue, setPastedValue] = useState("");
  const copyResetTimer = useRef<ReturnType<typeof setTimeout> | null>(null);

  const payload = useMemo(
    () => generateInvisibleText(selectedId, count),
    [selectedId, count],
  );
  const verification = useMemo(
    () => verifyPasteBack(expectedPayload, pastedValue),
    [expectedPayload, pastedValue],
  );
  const verificationLabel = verificationLabels[verification.status];
  const displayedCodePoints = verification.analysis.codePoints.slice(0, 40);

  useEffect(() => () => {
    if (copyResetTimer.current) clearTimeout(copyResetTimer.current);
  }, []);

  function updateCount(value: number) {
    setCount(clampInvisibleCount(value));
    setCopyState("idle");
  }

  async function copyPayload() {
    setExpectedPayload(payload);
    let copied = false;
    try {
      if (navigator.clipboard?.writeText) {
        await navigator.clipboard.writeText(payload);
        copied = true;
      } else {
        copied = fallbackCopy(payload);
      }
    } catch {
      copied = fallbackCopy(payload);
    }

    setCopyState(copied ? "copied" : "failed");
    if (copyResetTimer.current) clearTimeout(copyResetTimer.current);
    if (copied) {
      trackToolStarted("invisible-text");
      trackToolEvent("invisible-text", "copy_completed");
      copyResetTimer.current = setTimeout(() => setCopyState("idle"), 1500);
    }
  }

  return (
    <section className="generator-shell" aria-labelledby="generator-title">
      <div className="generator-heading">
        <div>
          <span className="section-label">Browser-local tool</span>
          <h2 id="generator-title">Build your invisible text</h2>
          <p>Choose a character, set a quantity, then copy the exact Unicode payload.</p>
        </div>
        <span className="local-badge"><ShieldCheck size={17} /> Nothing is uploaded</span>
      </div>

      <fieldset className="character-picker">
        <legend>1. Choose a character</legend>
        <p className="field-help">General blank is a recommended test starting point, not a universal compatibility promise.</p>
        <div className="character-grid">
          {INVISIBLE_CHARACTERS.map((character) => (
            <label className="character-option" key={character.id}>
              <input
                checked={selectedId === character.id}
                name="invisible-character"
                onChange={() => {
                  setSelectedId(character.id);
                  setCopyState("idle");
                }}
                type="radio"
                value={character.id}
              />
              <span className="character-option-body">
                <span className="character-option-title">
                  <strong>{character.name}</strong>
                  {character.recommended ? <em>Start here</em> : null}
                </span>
                <code>{character.codePoint}</code>
                <span>{character.width} · Category {character.unicodeCategory}</span>
                <small>{character.caution}</small>
              </span>
            </label>
          ))}
        </div>
      </fieldset>

      <div className="quantity-block">
        <label htmlFor="invisible-count">2. Set the quantity</label>
        <div className="quantity-control">
          <button aria-label="Decrease quantity" onClick={() => updateCount(count - 1)} type="button"><Minus size={18} /></button>
          <input
            id="invisible-count"
            inputMode="numeric"
            max={500}
            min={1}
            onChange={(event) => updateCount(Number(event.target.value))}
            type="number"
            value={count}
          />
          <button aria-label="Increase quantity" onClick={() => updateCount(count + 1)} type="button"><Plus size={18} /></button>
        </div>
        <div className="quick-counts" aria-label="Quick quantities">
          {quickCounts.map((value) => (
            <button className={count === value ? "active" : ""} key={value} onClick={() => updateCount(value)} type="button">{value}</button>
          ))}
        </div>
      </div>

      <div className="payload-preview">
        <div>
          <span>Payload preview</span>
          <strong>{count} invisible {count === 1 ? "character" : "characters"}</strong>
        </div>
        <div className="token-ruler" aria-hidden="true">
          {Array.from({ length: Math.min(count, 24) }, (_, index) => <i key={index} />)}
          {count > 24 ? <b>+{count - 24}</b> : null}
        </div>
        <p>The markers show quantity only. They are not part of the copied text.</p>
      </div>

      <button className={`copy-primary ${copyState}`} onClick={copyPayload} type="button">
        {copyState === "copied" ? <ClipboardCheck size={20} /> : <Copy size={20} />}
        {copyState === "copied" ? "Copied" : "Copy invisible text"}
      </button>
      <p className="sr-only" aria-live="polite">
        {copyState === "copied" ? `${count} invisible characters copied.` : copyState === "failed" ? "Automatic copy failed. Use the manual copy field." : ""}
      </p>

      {copyState === "failed" ? (
        <div className="copy-fallback" role="alert">
          <strong>Automatic copy did not work.</strong>
          <p>Select the field below and use your device&apos;s copy command.</p>
          <textarea aria-label="Invisible text for manual copy" onFocus={(event) => event.currentTarget.select()} readOnly value={payload} />
        </div>
      ) : null}

      <details className="verifier">
        <summary><Clipboard size={19} /> Test what survived after pasting</summary>
        <div className="verifier-body">
          <div className="verifier-intro">
            <h3>Paste-back verifier</h3>
            <p>Paste the generated text into your target, copy it back, then paste it below. BriefVu compares code points locally—it cannot inspect another app directly.</p>
          </div>
          <label htmlFor="paste-back">Paste the returned value</label>
          <textarea
            id="paste-back"
            onChange={(event) => setPastedValue(event.target.value)}
            placeholder="Paste back here…"
            value={pastedValue}
          />
          <div className={`verification-result ${verificationLabel.tone}`} aria-live="polite">
            {verification.status === "exact_match" ? <Check size={20} /> : <RotateCcw size={20} />}
            <div><strong>{verificationLabel.title}</strong><p>{verificationLabel.detail}</p></div>
          </div>
          <div className="analysis-grid">
            <div><span>Total code points</span><strong>{verification.analysis.totalCodePoints}</strong></div>
            <div><span>Supported characters</span><strong>{verification.analysis.supportedCharacters}</strong></div>
            <div><span>Other whitespace</span><strong>{verification.analysis.otherWhitespace}</strong></div>
            <div><span>Other code points</span><strong>{verification.analysis.otherCodePoints}</strong></div>
          </div>
          {displayedCodePoints.length ? (
            <div className="code-point-list" aria-label="Detected code points">
              {displayedCodePoints.map((codePoint, index) => <code key={`${codePoint}-${index}`}>{codePoint}</code>)}
              {verification.analysis.codePoints.length > displayedCodePoints.length ? <span>+{verification.analysis.codePoints.length - displayedCodePoints.length} more</span> : null}
            </div>
          ) : null}
          <button className="clear-verifier" onClick={() => setPastedValue("")} type="button">Clear test area</button>
          <p className="normalization-note">Note: U+3164 may normalize to U+1160 under NFKC, and U+00A0 may normalize to an ordinary space. Platforms can also strip or replace characters.</p>
        </div>
      </details>
    </section>
  );
}
